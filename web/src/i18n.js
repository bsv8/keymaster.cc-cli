export function setLang(l) {
  if (l === 'zh' || l === 'en' || l === 'ja') lang = l;
  else if (typeof l === 'string' && l.startsWith('ja')) lang = 'ja';
  else if (typeof l === 'string' && l.startsWith('en')) lang = 'en';
  else if (typeof l === 'string' && l.startsWith('zh')) lang = 'zh';
  else lang = 'zh';
}

export function getLang() { return lang; }

export function resolveLang(settingsLang) {
  if (settingsLang && settingsLang !== 'system') return settingsLang;
  if (typeof navigator !== 'undefined' && navigator.language) {
    const n = navigator.language.toLowerCase();
    if (n.startsWith('ja')) return 'ja';
    if (n.startsWith('en')) return 'en';
  }
  return 'zh';
}

// t(key, vars): vars replace {name} placeholders.
export function t(key, vars) {
  const d = D[lang] || {};
  let s = Object.prototype.hasOwnProperty.call(d, key) ? d[key] : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}
