// Package tray 是桌面托盘的内部实现：托盘作为同一个 km 进程的子进程
// 运行，只做状态展示、菜单与打开浏览器，不加载钱包、不读私钥、
// 不持有数据目录锁、不新增业务接口。
//
// 架构位置:
//
//	km daemon (daemonrun 编排)
//	 └─ 后台 Daemon：钱包、API、任务、锁（主体）
//	 └─ 托盘子进程：同一 km 二进制的内部入口，对外不可见
//
// 托盘失败或异常退出都不影响后台；只有后台启动失败才报错退出。
// 后台关闭时先完成收尾并释放锁，再关闭托盘。不重启托盘。
//
// # 通信
//
// 父子进程之间使用匿名管道传输换行分隔的 JSON 消息（一行一帧，UTF-8）。
// 父进程的标准输入输出不用于此通道：子进程的 stdin/stdout 即是管道两
// 端，stderr 用于诊断日志，绝不混入通信帧。每帧最大 1MiB，超限的帧被
// 丢弃并记错，不破坏后续帧的边界。
//
// 父 → 子：
//   - {"type":"status","state":"locked|unlocked|restarting|stopping",
//     "locked":bool,"network":"test|main","apiAddr":"127.0.0.1:PORT"|"",
//     "webAdmin":bool,"detail"?:string}
//   - {"type":"shutdown"}：有序关闭。子进程清理后退出码 0。
//
// 子 → 父：
//   - {"type":"ready"}：托盘就绪（图标已注册或已确认不可用并降级）。
//   - {"type":"action","action":"open-admin|restart|quit"}：菜单动作。
//
// 规则：
//   - 状态消息是全量快照，子进程不做差分、不缓存旧状态。
//   - apiAddr 必须由父进程根据实际监听地址生成；子进程不接受其他
//     来源的 URL，不打开任意链接（只允许 http/https 本机地址）。
//   - Web Admin 关闭时父进程在状态里标记，托盘禁用“打开管理页面”
//     并说明原因，而不是隐藏入口。
//   - "open-admin" 由子进程调用系统默认浏览器打开 apiAddr。
//   - "restart"/"quit" 只表达用户意图；是否执行、如何收尾由父进程的
//     生命周期控制器决定。托盘异常、管道异常绝不能被解释为用户退出。
//   - 父进程退出或管道关闭后，子进程必须自行退出（不留孤儿）。
//   - 子进程崩溃或异常退出后，父进程只记录错误（等级与退出码），
//     不重启托盘，后台继续运行。
//   - 启动超时（默认 5 秒）内未收到 ready 也未退出，视为启动失败：
//     结束子进程、记录错误，后台继续运行。
//
// 未知 type 的消息必须忽略并记录，不得中断连接；损坏的行（非法
// JSON、超限）在记录后跳过，连接保持可用。
// 宿主探测：托盘子进程启动时先探测托盘宿主是否存在（Linux：D-Bus 上
// 是否有 StatusNotifierWatcher；无会话总线或无宿主则直接报错退出，
// 不驻留无图标进程）。探测通过后再进入托盘事件循环并发送 ready。
// 父进程以后台继续运行作为唯一降级路径，不把“托盘不可用”当后台
// 启动失败。退出码约定：0=有序退出（收到 shutdown 并完成清理）；
// 非 0=启动失败或运行中崩溃，父进程只记录错误（等级+退出码）不重启，
// 后台继续运行。

